import assert from 'node:assert/strict';
import {inPond} from './art.js';
import {placementAt,findRoute,newBrain,chooseInterest,stepHabitat,supportHeight,canTravel} from './habitat.js';
import {EditHistory,encodeGarden,decodeGarden,snapshot} from './garden-state.js';
const fixed=()=>.4;
const prop=(id,type,x,z,size=1)=>({id,type,x,z,size,angle:0,variant:0,bloom:0,ready:true,revision:0});
const frog={...prop('frog','frog',1,1,.65),brain:newBrain(-10,fixed)};
const pad=prop('pad','lily',1.7,1,.7),world=[frog,pad];
assert(placementAt('lily',1,1,.7,[]).valid);
assert(!placementAt('lily',-5,4,.7,[]).valid,'pads stay in water');
assert(!placementAt('tree',1,1,1,[]).valid,'trees stay on land');
assert(!placementAt('rabbit',0,0,.65,[]).valid,'rabbits stay on land');
assert(placementAt('tree',-5,3,1,[]).valid);
assert(!placementAt('tree',-5,3,1,[prop('other','tree',-5.1,3)]).valid,'solid bases have space');
assert(placementAt('tree',-5,3,1,[prop('same','tree',-5,3)],'same').valid,'moving ignores the selected object');
assert.equal(chooseInterest(frog,world,fixed).target.id,'pad');
for(let t=0;t<7;t+=.05)stepHabitat(frog,world,t,.05,{random:fixed});
assert.equal(frog.brain.mode,'rest','frog reaches the pad and settles');
assert(Math.hypot(frog.x-pad.x,frog.z-pad.z)<.05);
assert(supportHeight(frog,world)>0,'frog rests above the pad');
const follower={...prop('f2','frog',2.2,1.1,.65),brain:newBrain(-10,fixed)};
assert.equal(chooseInterest(follower,[...world,follower],fixed),null,'a small pad is reserved by one frog');
const old={x:frog.x,z:frog.z};pad.x=2.6;pad.revision++;
stepHabitat(frog,world,8,.05,{random:fixed});
assert.equal(frog.brain.targetId,null,'moving a target makes the frog reconsider');
assert.deepEqual({x:frog.x,z:frog.z},old,'moving a pad never teleports its visitor');
assert.equal(supportHeight(frog,world),0);
for(let t=8;t<19;t+=.05)stepHabitat(frog,world,t,.05,{random:fixed});
assert.equal(frog.brain.targetId,'pad');
assert(Math.hypot(frog.x-pad.x,frog.z-pad.z)<.05,'frog walks/swims to the new position');
stepHabitat(frog,[frog],20,.05,{random:fixed});assert.equal(frog.brain.targetId,null,'removing a prop releases its visitor');
const start={x:-5,z:.2},goal={x:5.8,z:.2},route=findRoute(start,goal,'rabbit',[]);
assert(route?.length>1,'rabbit finds a route around the pond');
let p=start;
for(const q of route){
 const n=Math.ceil(Math.hypot(q.x-p.x,q.z-p.z)/.04);
 for(let i=1;i<=n;i++){const x=p.x+(q.x-p.x)*i/n,z=p.z+(q.z-p.z)*i/n;assert(!inPond(x,z),'every point of the route stays on land');assert(canTravel('rabbit',x,z,[]));}
 p=q;
}
const rabbit={...prop('r','rabbit',-5,2,.65),brain:newBrain(-10,fixed)},tree=prop('tree','tree',-5,3,1),flowers=prop('flowers','flowers',-4.7,1.4);
assert.equal(chooseInterest(rabbit,[rabbit,tree],fixed).target.type,'tree');
assert.equal(chooseInterest(rabbit,[rabbit,flowers],fixed).point.activity,'nibble');
for(let t=0;t<9;t+=.05)stepHabitat(rabbit,[rabbit,tree],t,.05,{random:fixed});
assert.equal(rabbit.brain.mode,'rest');assert.equal(rabbit.brain.activity,'rest');
const displaced={...prop('displaced','rabbit',-5,3,.65),brain:newBrain(-10,fixed)},overlap=prop('overlap','tree',-5,3,1);
for(let t=0;t<8;t+=.05)stepHabitat(displaced,[displaced,overlap],t,.05,{random:fixed});
assert(Math.hypot(displaced.x-overlap.x,displaced.z-overlap.z)>.3,'an animal can step out when a tree is placed over it');
const journal=new EditHistory(),before=snapshot(tree);tree.x-=.4;const after=snapshot(tree);journal.record(before,after);
const undo=journal.undo();assert.equal(undo.value.x,before.x);assert.equal(journal.redo().value.x,after.x);
journal.undo();journal.record(null,snapshot(flowers));assert.equal(journal.redo(),null,'new edit clears the redo branch');
const saved=encodeGarden([tree,pad]);assert.equal(decodeGarden(saved).objects.length,2);assert.equal(decodeGarden('{bad'),null);assert.equal(decodeGarden(JSON.stringify({version:1,objects:[{...before,x:Infinity}]})),null);
assert.equal(decodeGarden(JSON.stringify({version:1,objects:[before,before]})),null,'duplicate ids are rejected');
assert.equal(decodeGarden(JSON.stringify({version:1,objects:[{...before,type:'toString'}]})),null,'unknown object types are rejected');
assert.deepEqual(decodeGarden(encodeGarden([])).objects,[],'an intentionally empty garden stays empty');
console.log('Placement, water-safe routes, environmental responses, retargeting, undo/redo and saved garden checks passed');
